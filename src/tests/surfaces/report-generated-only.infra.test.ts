// SPEC LINK: docs/specs/02-web-admin/128_surface_standard_policy.md Rule 19 (generated output is byte-identical to a regenerate: no hand-written scenario field),
//            docs/specs/02-web-admin/135_mcfrontend_decisions_register.md FE-02 (P1 declared, not coded),
//            docs/specs/02-web-admin/127_surface_conversion_procedure.md 4.3 (the capture script),
//            docs/specs/01-pipeline/124_step_standard_policy.md R-HM (generated outputs are never hand-edited).
//
// MF-16 · McFrontend queue · lane T. The FE-02 lock, the single named lock for Rule 19. One table of generated REPORT output classes:
//   seed classes   report-v2.decl.json, report-v2-seed/catalogue-fields.json, report-presentation.json: checked by the committed generator
//                  `seed-report-v2.mjs --check` run on a sandbox copy (the idiom of report-generator.logic.test.ts);
//   golden class   one golden file per state and target: checked by captureAll(root) from scripts/surfaces/report-capture.ts, exact text compare.
// For each class: control (an untouched copy is current), then a planted hand edit (dead-man: the bytes changed), RED (seed: exit 1 and
// `GEN-HAND-EDIT <file>`; golden: the compare names the stale file), then the regenerate restores it byte for byte and the check is GREEN.
// Overlap, stated: report-generator.logic.test.ts Case 3 already covers decl/presentation/rulings hand edits, and report-render.logic.test.ts T1
// goes red on any golden edit. This file is the one lock FE-02 names, and adds the golden class and catalogue-fields.json.
// Note: row-presentation.json is a generator INPUT (an edit gives GEN-STALE), not a generated output, so it is not in the table.
// captureAll writes nothing and builds trees with the repo's ctx, so a golden restore here is a write of the captured text in the sandbox (the
// 5-line loop of report-capture.ts main, stated). The gate (surface-validate --check) does not catch a golden edited identically in all four
// targets; this lock does, through captureAll (queue card MF-16-F1). No DB, no network.
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { captureAll } from '../../../scripts/surfaces/report-capture';
import { GOLDEN_DIR, TARGETS } from '../../../scripts/surfaces/report-checks.mjs';

type Json = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any -- untyped JSON documents
const ROOT = process.cwd();
const SCHEMA_DIR = 'scripts/surfaces/_schema';
const GEN = `${SCHEMA_DIR}/seed-report-v2.mjs`;
const CATALOGUE = 'scripts/seeds/bylaw/layer3-catalogue.json';
const SWITCHBOARD = 'scripts/seeds/bylaw/switchboard.json';
const Q7_LOG = 'docs/reports/decisions/2026-10-20-chat-batch-b.json';
// The seed classes: generated by the generator, checked by its --check.
const SEED_CLASSES = [`${SCHEMA_DIR}/report-v2.decl.json`, `${SCHEMA_DIR}/report-v2-seed/catalogue-fields.json`, `${SCHEMA_DIR}/report-presentation.json`];
// The golden class: one file per state and target of the manifest, read from the sandbox copy.
const GOLDEN_SAMPLE = `${GOLDEN_DIR}/permitted.web.json`;

let tmpRoot = '';
beforeAll(() => { tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'mf16-genonly-')); });
afterAll(() => { fs.rmSync(tmpRoot, { recursive: true, force: true }); });

// A throwaway tree: bytes copied from the tree under test, so the control proves the copy is faithful.
const sandbox = (): string => {
  const dir = fs.mkdtempSync(path.join(tmpRoot, 'tree-'));
  fs.cpSync(path.join(ROOT, SCHEMA_DIR), path.join(dir, SCHEMA_DIR), { recursive: true });
  fs.cpSync(path.join(ROOT, GOLDEN_DIR), path.join(dir, GOLDEN_DIR), { recursive: true });
  for (const rel of [CATALOGUE, SWITCHBOARD, Q7_LOG]) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.copyFileSync(path.join(ROOT, rel), path.join(dir, rel));
  }
  return dir;
};
const readJson = (dir: string, rel: string): Json => JSON.parse(fs.readFileSync(path.join(dir, rel), 'utf8'));
const writeJson = (dir: string, rel: string, doc: Json): void => fs.writeFileSync(path.join(dir, rel), `${JSON.stringify(doc, null, 2)}\n`);
const sha = (dir: string, rel: string): string => crypto.createHash('sha256').update(fs.readFileSync(path.join(dir, rel))).digest('hex');
const gen = (dir: string, mode: '--check' | '--write'): { status: number | null; err: string; out: string } => {
  const r = spawnSync(process.execPath, [path.join(dir, GEN), mode], { cwd: dir, encoding: 'utf8', timeout: 60000 });
  return { status: r.status, err: r.stderr, out: r.stdout };
};
// The golden check: the files whose text differs from the capture of the sandbox.
const staleGoldens = (dir: string): string[] => {
  const stale: string[] = [];
  for (const [name, text] of captureAll(dir)) if (fs.readFileSync(path.join(dir, GOLDEN_DIR, name), 'utf8') !== text) stale.push(name);
  return stale.sort();
};
const restoreGoldens = (dir: string): void => {
  for (const [name, text] of captureAll(dir)) fs.writeFileSync(path.join(dir, GOLDEN_DIR, name), text);
};
const handEdit = (dir: string, rel: string): void => {
  const doc = readJson(dir, rel);
  doc.hand_edit = 'MF-16 probe';
  writeJson(dir, rel, doc);
};
const editTree = (dir: string, rel: string): void => {
  const doc = readJson(dir, rel);
  doc.rendered_tree.nodes[0].value = `${String(doc.rendered_tree.nodes[0].value)} (hand edit)`;
  writeJson(dir, rel, doc);
};

describe('FE-02 controls: an untouched copy is current in every class', () => {
  it('the seed classes reproduce from their inputs (generator --check exit 0)', () => {
    const r = gen(sandbox(), '--check');
    expect(r.out).toContain('current');
    expect(r.status).toBe(0);
  });
  it('the golden class reproduces from the capture (no stale file; all 44 files compared)', () => {
    const dir = sandbox();
    expect(captureAll(dir).size).toBe(44);
    expect(staleGoldens(dir)).toEqual([]);
  });
});

describe('FE-02 RED: a hand edit of a generated seed file', () => {
  it.each(SEED_CLASSES)('%s: exit 1 and GEN-HAND-EDIT naming the file', (rel) => {
    const dir = sandbox();
    const before = sha(dir, rel);
    handEdit(dir, rel);
    expect(sha(dir, rel)).not.toBe(before); // dead-man: the edit really changed the file
    const r = gen(dir, '--check');
    expect(r.status).toBe(1);
    expect(r.err).toContain(`GEN-HAND-EDIT ${rel}`);
    expect(r.err).not.toContain('GEN-STALE');
  });
  it('--write restores every edited seed file byte for byte, and --check is then GREEN', () => {
    const dir = sandbox();
    const before = SEED_CLASSES.map((f) => sha(dir, f));
    for (const rel of SEED_CLASSES) handEdit(dir, rel);
    expect(SEED_CLASSES.map((f) => sha(dir, f))).not.toEqual(before);
    expect(gen(dir, '--write').status).toBe(0);
    expect(SEED_CLASSES.map((f) => sha(dir, f))).toEqual(before);
    expect(gen(dir, '--check').status).toBe(0);
  });
});

describe('FE-02 RED: a hand edit of a golden file', () => {
  it('one target file: the compare names exactly that file', () => {
    const dir = sandbox();
    const before = sha(dir, GOLDEN_SAMPLE);
    editTree(dir, GOLDEN_SAMPLE);
    expect(sha(dir, GOLDEN_SAMPLE)).not.toBe(before); // dead-man
    expect(staleGoldens(dir)).toEqual(['permitted.web.json']);
  });
  it('the same edit made identically in all four targets of a state: all four are named (the gate does not see this; card MF-16-F1)', () => {
    const dir = sandbox();
    const rels = (TARGETS as string[]).map((t) => `${GOLDEN_DIR}/permitted.${t}.json`);
    const before = rels.map((r) => sha(dir, r));
    for (const r of rels) editTree(dir, r);
    expect(rels.map((r) => sha(dir, r))).not.toEqual(before);
    expect(staleGoldens(dir)).toEqual((TARGETS as string[]).map((t) => `permitted.${t}.json`).sort());
  });
  it('the regenerate restores the golden byte for byte, and the compare is then GREEN', () => {
    const dir = sandbox();
    const before = sha(dir, GOLDEN_SAMPLE);
    editTree(dir, GOLDEN_SAMPLE);
    restoreGoldens(dir);
    expect(sha(dir, GOLDEN_SAMPLE)).toBe(before);
    expect(staleGoldens(dir)).toEqual([]);
  });
});
