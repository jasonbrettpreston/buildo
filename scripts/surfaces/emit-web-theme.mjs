// MF-37 · McFrontend queue. Emits the Mantine theme from ONE token source: the @theme `--color-*` hex vars of src/app/globals.css
// plus scripts/surfaces/_schema/web-theme.json (amber tuple, on-primary, contrast pairs). The output holds JSON only (colour keys +
// other.onPrimary); the client provider merges it. Pure over committed files; no DB, no network.
// CLI: --write writes the generated file; --check (default) prints problem lines and exits 1, else prints `theme ok (N pairs, S shades)`.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const CSS_FILE = 'src/app/globals.css';
export const SPEC_FILE = 'scripts/surfaces/_schema/web-theme.json';
export const OUT_FILE = 'src/lib/surfaces/web/theme.generated.json';
const COMMENT = 'GENERATED by scripts/surfaces/emit-web-theme.mjs — do not edit';
const SHA_RE = /input_sha ([0-9a-f]{16})/;
const HEX_RE = /^#[0-9a-fA-F]{6}$/;
const FIXED = { white: '#ffffff', black: '#000000' };

/** The `--color-*: #hex;` declarations inside the `@theme { ... }` block → { '--color-x': '#hex' }. */
export function parseThemeVars(cssText) {
  const vars = {};
  const start = cssText.search(/@theme\s*\{/);
  if (start < 0) return vars;
  const open = cssText.indexOf('{', start);
  let depth = 0;
  let end = open;
  for (let i = open; i < cssText.length; i += 1) {
    if (cssText[i] === '{') depth += 1;
    else if (cssText[i] === '}') {
      depth -= 1;
      if (depth === 0) { end = i; break; }
    }
  }
  const body = cssText.slice(open + 1, end).replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of body.matchAll(/(--color-[\w-]+)\s*:\s*(#[0-9a-fA-F]{6})\s*;/g)) vars[m[1]] = m[2];
  return vars;
}

/** sha256 (first 16 hex) of the two inputs: the @theme colour vars (sorted) and the parsed web-theme.json. */
export function inputSha(themeSpec, vars) {
  const sorted = Object.fromEntries(Object.keys(vars).sort().map((k) => [k, vars[k]]));
  return crypto.createHash('sha256').update(JSON.stringify({ vars: sorted, spec: themeSpec })).digest('hex').slice(0, 16);
}

function luminance(hex) {
  const n = hex.replace('#', '');
  const ch = [0, 2, 4].map((i) => Number(`0x${n.slice(i, i + 2)}`) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}

/** WCAG 2.1 contrast ratio of two #rrggbb colours (unrounded). */
export function contrastRatio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const fmt = (r) => (Math.floor(r * 100) / 100).toFixed(2);

/** themeSpec + vars → { theme, problems, pairs: [{fg,bg,role,ratio,min}], shades }. Theme key order is fixed. */
export function buildTheme(themeSpec, vars, sha = inputSha(themeSpec, vars)) {
  const problems = [];
  const resolve = (v) => {
    if (v && typeof v === 'object' && typeof v.token === 'string') {
      if (!(v.token in vars)) { problems.push(`THEME-TOKEN ${v.token}: not in globals.css`); return null; }
      return vars[v.token].toLowerCase();
    }
    if (typeof v === 'string' && HEX_RE.test(v)) return v.toLowerCase();
    problems.push(`THEME-SHAPE ${JSON.stringify(v)}: not a #rrggbb hex or {"token"}`);
    return null;
  };
  const tuples = { amber: themeSpec.amber, ...(themeSpec.colors ?? {}) };
  const colors = {};
  const literal = []; // [key.index] of every non-bound shade
  for (const [key, tuple] of Object.entries(tuples)) {
    if (!Array.isArray(tuple) || tuple.length !== 10) {
      problems.push(`THEME-SHAPE ${key}: ${Array.isArray(tuple) ? tuple.length : 0} entries (need 10)`);
      continue;
    }
    colors[key] = tuple.map(resolve);
    tuple.forEach((v, i) => { if (typeof v === 'string') literal.push(`${key}.${i}`); });
  }
  const onPrimary = resolve(themeSpec.on_primary);
  const refColour = (ref) => {
    if (ref === 'on_primary') return onPrimary;
    if (ref in FIXED) return FIXED[ref];
    if (typeof ref === 'string' && HEX_RE.test(ref)) return ref.toLowerCase();
    const m = /^([a-z][\w-]*)\.(\d)$/.exec(String(ref));
    return m && colors[m[1]] ? colors[m[1]][Number(m[2])] : null;
  };
  const minimum = themeSpec.contrast?.minimum ?? {};
  const pairs = [];
  const covered = new Set();
  for (const p of themeSpec.contrast?.pairs ?? []) {
    const fg = refColour(p.fg);
    const bg = refColour(p.bg);
    const min = minimum[p.role];
    if (!fg || !bg || typeof min !== 'number') {
      problems.push(`THEME-CONTRAST ${p.fg}/${p.bg}: unresolved (fg, bg or role "${p.role}")`);
      continue;
    }
    const ratio = contrastRatio(fg, bg);
    pairs.push({ fg: p.fg, bg: p.bg, role: p.role, ratio: Number(fmt(ratio)), min });
    if (ratio < min) problems.push(`THEME-CONTRAST ${p.fg}/${p.bg}: ${fmt(ratio)} < ${min}`);
    covered.add(p.fg);
    covered.add(p.bg);
  }
  if ((themeSpec.contrast?.pairs ?? []).length === 0) problems.push('THEME-CONTRAST: no pairs');
  for (const shade of literal) if (!covered.has(shade)) problems.push(`THEME-CONTRAST ${shade}: no pair`);
  const theme = {
    $comment: `${COMMENT} (input_sha ${sha})`,
    primaryColor: themeSpec.primaryColor,
    primaryShade: themeSpec.primaryShade,
    colors,
    other: { onPrimary },
  };
  return { theme, problems, pairs, shades: literal.length };
}

export const serialize = (theme) => `${JSON.stringify(theme, null, 2)}\n`;

function readInputs(root, over) {
  const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
  const cssText = over.cssText ?? read(CSS_FILE);
  const specText = over.specText ?? read(SPEC_FILE);
  let generatedText = over.generatedText;
  if (generatedText === undefined) {
    const p = path.join(root, OUT_FILE);
    generatedText = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
  }
  return { vars: parseThemeVars(cssText), themeSpec: JSON.parse(specText), generatedText };
}

/** Full check. `over` = optional in-memory { cssText, specText, generatedText } in place of the files under root (null generatedText = missing). */
export function checkTheme(root = REPO, over = {}) {
  const { vars, themeSpec, generatedText } = readInputs(root, over);
  const sha = inputSha(themeSpec, vars);
  const built = buildTheme(themeSpec, vars, sha);
  const lines = [...built.problems];
  const fresh = serialize(built.theme);
  if (generatedText !== fresh) {
    const stored = SHA_RE.exec(generatedText ?? '')?.[1];
    lines.push(stored === sha ? `GEN-HAND-EDIT ${OUT_FILE}` : `GEN-STALE ${OUT_FILE}`);
  }
  const note = lines.length === 0
    ? `theme ok (${built.pairs.length} pairs, ${built.shades} shades)`
    : `theme FAIL (${lines.length} problem${lines.length === 1 ? '' : 's'})`;
  return { lines, note, pairs: built.pairs };
}

function main(argv) {
  if (argv.includes('--write')) {
    const { vars, themeSpec } = readInputs(REPO, { generatedText: null });
    const built = buildTheme(themeSpec, vars);
    if (built.problems.length) {
      for (const l of built.problems) console.error(l);
      console.error('emit-web-theme: not written (fix the problems above)');
      process.exitCode = 1;
      return;
    }
    const out = path.join(REPO, OUT_FILE);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, serialize(built.theme));
    console.log(`wrote ${OUT_FILE} (${built.pairs.length} pairs, ${built.shades} shades)`);
    return;
  }
  const { lines, note } = checkTheme(REPO);
  for (const l of lines) console.log(l);
  console.log(note);
  if (lines.length) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
