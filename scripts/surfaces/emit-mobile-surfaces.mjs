#!/usr/bin/env node
// SPEC LINK: docs/specs/02-web-admin/126_maxbld_surface_standard.md §11b.2 (descriptor + content -> generator -> binding; regenerated, never
//            hand-edited), docs/specs/02-web-admin/135_mcfrontend_decisions_register.md FE-02 (generated, not hand-written), FE-31.
//
// MF-35 · McFrontend queue (plan v2 §2.1, §2.3; v3 §2.3). The mobile app cannot read files outside mobile/, so this generator copies, for every
// converted surface whose descriptor declares the mobile platform:
//   mobile/src/generated/surfaces/<id>.json                 the slice the binding reads: the descriptor's config values and the content strings;
//   mobile/__tests__/fixtures/surfaces/<id>.goldens.json    the committed mobile goldens (src/tests/fixtures/surfaces/<id>/*.mobile.json), for
//                                                            the mobile jest golden test (kept out of the app bundle).
// One source each: the descriptor, the content file, the goldens. Pure over committed files; no DB, no network.
// CLI: --write writes every output and removes the GEN-STRAY files (task-454 L8: a stray slice or golden copy no converted surface owns; nothing else in the
// two dirs); --check (default) prints GEN-STALE / GEN-HAND-EDIT / GEN-STRAY lines and exits 1, else prints `surfaces ok (N surfaces, G goldens)`.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MANIFEST = 'scripts/surfaces/_schema/converted-surfaces.json';
const PAGE_TABLE = 'scripts/surfaces/_schema/static-page.json'; // PAGE.TABLE (task-390): `screens`, the rows of an interactive page
const PRESENTATION = 'scripts/surfaces/_schema/report-presentation.json'; // MF-48 Stage B: the REPORT lifecycle texts
const GOLDEN_ROOT = 'src/tests/fixtures/surfaces';
export const SLICE_DIR = 'mobile/src/generated/surfaces';
export const GOLDEN_COPY_DIR = 'mobile/__tests__/fixtures/surfaces';
const COMMENT = 'GENERATED by scripts/surfaces/emit-mobile-surfaces.mjs — do not edit';
const SHA_RE = /input_sha ([0-9a-f]{16})/;
// The descriptor config values a mobile surface may read: the SEARCH archetype's declared parameters (Spec 126 §3.1 row 4: debounce_ms, min_query_len) and
// the phone tunables FIX.TUNE (task-378) moved out of code (Spec 126 P4: continue_wait_ms on the semi page; entitlement_stale_ms, lookup_retry_max, lookup_stale_ms on the search page).
// FIX.CONFIG-BOUNDS (task-395; Spec 128 Rule 3; operator, verbatim, 2026-11-20: "yes follow the rules register them.", MORNING-DECISIONS.md:1494): each key is a REGISTERED logic
// variable, named here (one map: config key -> seed row). The slice number is resolved from that seed row (scripts/seeds/logic_variables.json) at generate time and the slice carries the
// row's bounds beside it (`bounds.<key>`), which mobile/src/lib/sliceConfig.ts applies. Only the phone reads the slice; no web binding reads these keys today.
// task-454 SEARCHFIX.6 (same ruling and rule): candidate_cap and recent_max of the search page join them (the cap is also read by the server, from the same row).
const SEED = 'scripts/seeds/logic_variables.json';
const SCHEMA_FILE = 'scripts/surfaces/_schema/surface.schema.json';
export const PAGE_SETTINGS = {
  debounce_ms: 'maxbld_page_debounce_ms',
  min_query_len: 'maxbld_page_min_query_len',
  continue_wait_ms: 'maxbld_page_continue_wait_ms',
  entitlement_stale_ms: 'maxbld_page_entitlement_stale_ms',
  lookup_retry_max: 'maxbld_page_lookup_retry_max',
  lookup_stale_ms: 'maxbld_page_lookup_stale_ms',
  candidate_cap: 'maxbld_page_candidate_cap',
  recent_max: 'maxbld_page_recent_max',
};
const CONFIG_KEYS = Object.keys(PAGE_SETTINGS);
/**
 * task-454 L4 (g3 GROUNDER-D D4): the smallest number of each key that needs a config.logic_variables entry, read once from the schema's own per-key rule
 * (config.allOf[].if.properties.<key>.minimum): 1 for debounce_ms and min_query_len (a 0 there states that a binding module has no such setting), 0 for
 * every other key, and for a key whose rule names no minimum (so its entry stays required for every number, 0 included). Schema data, not a key list.
 */
const CONFIG_RULES = JSON.parse(fs.readFileSync(path.join(REPO, SCHEMA_FILE), 'utf8')).properties?.config?.allOf ?? [];
export const ENTRY_FROM = Object.fromEntries(CONFIG_KEYS.map((k) => {
  const min = CONFIG_RULES.find((r) => r?.if?.required?.[0] === k)?.if?.properties?.[k]?.minimum;
  return [k, typeof min === 'number' ? min : 0];
}));

/**
 * The registered bounds of each number in `config`, and the problem lines: a number whose descriptor declares no config.logic_variables entry for its seed row, a seed row that
 * is absent, an entry whose on_invalid is not fail or clamp, an entry whose min or max differs from the row, a descriptor value that is not the row's default, a value outside
 * min and max. The bounds carry min and max from the seed row and on_invalid from the descriptor entry. Only numbers are judged: a config holding only UNRESEARCHED keys
 * gives {} and no problem; a number below ENTRY_FROM of its key (a 0 the schema allows without an entry) is emitted as it is, with no bounds. Pure over its arguments.
 */
export function pageSettingBounds(config, entries, seed) {
  const bounds = {};
  const problems = [];
  for (const [k, v] of Object.entries(config ?? {})) {
    if (typeof v !== 'number' || v < (ENTRY_FROM[k] ?? 0)) continue;
    const name = PAGE_SETTINGS[k];
    const entry = Array.isArray(entries) ? entries.find((e) => e && e.name === name) : undefined;
    const row = seed?.[name];
    if (entry === undefined) { problems.push(`config.${k}: no config.logic_variables entry named ${name}`); continue; }
    if (row === undefined || row === null || typeof row.min !== 'number' || typeof row.max !== 'number' || typeof row.default !== 'number') { problems.push(`config.${k}: seed row ${name} is absent or not a bounded number`); continue; }
    if (!(entry.on_invalid === 'fail' || entry.on_invalid === 'clamp')) { problems.push(`config.${k}: on_invalid must be fail or clamp`); continue; }
    if (entry.min !== row.min || entry.max !== row.max) { problems.push(`config.${k}: the descriptor bounds ${entry.min} to ${entry.max} differ from seed row ${name} (${row.min} to ${row.max})`); continue; }
    if (v !== row.default) { problems.push(`config.${k}: ${v} differs from the seed default ${row.default} of ${name}`); continue; }
    if (v < row.min || v > row.max) { problems.push(`config.${k}: ${v} is outside its bounds ${row.min} to ${row.max}`); continue; }
    bounds[k] = { min: row.min, max: row.max, on_invalid: entry.on_invalid };
  }
  return { bounds, problems };
}

const rj = (root, rel) => JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));
const descriptorFile = (root, id) => {
  const walk = (rel) => fs.readdirSync(path.join(root, rel), { withFileTypes: true }).flatMap((e) => {
    const r = path.posix.join(rel, e.name);
    if (e.isDirectory()) return e.name === '_schema' ? [] : walk(r);
    return e.name === `${id}.descriptor.json` ? [r] : [];
  });
  const found = walk('scripts/surfaces');
  if (found.length !== 1) throw new Error(`emit-mobile-surfaces: ${found.length} descriptor files for ${id}`);
  return found[0];
};
const sha = (v) => crypto.createHash('sha256').update(JSON.stringify(v)).digest('hex').slice(0, 16);
const text = (v) => `${JSON.stringify(v, null, 2)}\n`;

/** Every output file (repo-relative) -> its exact text. */
export function buildOutputs(root = REPO) {
  const out = new Map();
  const screens = rj(root, PAGE_TABLE).screens ?? {};
  const seed = rj(root, SEED);
  for (const id of rj(root, MANIFEST).converted) {
    const file = descriptorFile(root, id);
    const d = rj(root, file);
    if (!(d.identity?.platforms ?? []).includes('mobile')) continue;
    const content = rj(root, path.posix.join(path.posix.dirname(file), `${id}.content.json`));
    const config = Object.fromEntries(CONFIG_KEYS.filter((k) => d.config?.[k] !== undefined).map((k) => [k, d.config[k]]));
    const { bounds, problems } = pageSettingBounds(config, d.config?.logic_variables, seed);
    if (problems.length > 0) throw new Error(`emit-mobile-surfaces: ${id}: ${problems.join('; ')}`);
    // PAGE.TABLE (task-390): a surface with a screen in the page table carries its rows in the slice (one source; the binding draws them).
    const slice = { surface: id, config, ...(Object.keys(bounds).length > 0 ? { bounds } : {}), content, ...(screens[id] === undefined ? {} : { page: screens[id] }) };
    out.set(`${SLICE_DIR}/${id}.json`, text({ $comment: `${COMMENT} (input_sha ${sha(slice)})`, ...slice }));
    const gdir = path.join(root, GOLDEN_ROOT, id);
    const names = fs.existsSync(gdir) ? fs.readdirSync(gdir).filter((f) => f.endsWith('.mobile.json')).sort() : [];
    const goldens = Object.fromEntries(names.map((f) => [f.slice(0, -'.mobile.json'.length), rj(root, `${GOLDEN_ROOT}/${id}/${f}`)]));
    out.set(`${GOLDEN_COPY_DIR}/${id}.goldens.json`, text({ $comment: `${COMMENT} (input_sha ${sha(goldens)})`, surface: id, goldens }));
  }
  // MF-48 Stage B (Spec 126 §11a.7 dated note 2026-11-12): a REPORT surface on mobile (the manifest's `report` list) gets a slice too: the approved
  // lifecycle texts of report-presentation.json (`states.lifecycle.<state>`, one home, never copied by hand) and its own content file (Retry, Back).
  // No goldens copy: its props goldens are read from the repo path by the mobile golden test (MF-48 Stage A, plan v2 L-5).
  for (const id of rj(root, MANIFEST).report ?? []) {
    const file = descriptorFile(root, id);
    if (!(rj(root, file).identity?.platforms ?? []).includes('mobile')) continue;
    const life = rj(root, PRESENTATION).states.lifecycle;
    const own = rj(root, path.posix.join(path.posix.dirname(file), `${id}.content.json`));
    const content = { ...Object.fromEntries(Object.entries(life).map(([k, v]) => [`states.lifecycle.${k}`, v])), ...own };
    const slice = { surface: id, config: {}, content };
    out.set(`${SLICE_DIR}/${id}.json`, text({ $comment: `${COMMENT} (input_sha ${sha(slice)})`, ...slice }));
  }
  return out;
}

/** Problem lines: a stale or hand-edited output, or a stray generated file no converted mobile surface owns. */
export function checkOutputs(root = REPO, outputs = buildOutputs(root)) {
  const lines = [];
  for (const [rel, fresh] of outputs) {
    const p = path.join(root, rel);
    const stored = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (stored === fresh) continue;
    lines.push(SHA_RE.exec(stored ?? '')?.[1] === SHA_RE.exec(fresh)?.[1] ? `GEN-HAND-EDIT ${rel}` : `GEN-STALE ${rel}`);
  }
  for (const [dir, suffix] of [[SLICE_DIR, '.json'], [GOLDEN_COPY_DIR, '.goldens.json']]) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs)) continue;
    for (const f of fs.readdirSync(abs).filter((x) => x.endsWith(suffix)).sort()) if (!outputs.has(`${dir}/${f}`)) lines.push(`GEN-STRAY ${dir}/${f}`);
  }
  return lines;
}

/** task-454 L8 (g3 GROUNDER-F D10): write every output, then remove each file checkOutputs names GEN-STRAY (only those; a file already gone is no error). */
export function writeOutputs(root = REPO, outputs = buildOutputs(root)) {
  for (const [rel, t] of outputs) {
    fs.mkdirSync(path.dirname(path.join(root, rel)), { recursive: true });
    fs.writeFileSync(path.join(root, rel), t);
  }
  const stray = checkOutputs(root, outputs).filter((l) => l.startsWith('GEN-STRAY ')).map((l) => l.slice('GEN-STRAY '.length));
  for (const rel of stray) fs.rmSync(path.join(root, rel), { force: true });
  return { written: outputs.size, removed: stray };
}

function main(argv) {
  const outputs = buildOutputs(REPO);
  if (argv.includes('--write')) {
    const { written, removed } = writeOutputs(REPO, outputs);
    console.log(`wrote ${written} files${removed.length ? `, removed ${removed.length} stray: ${removed.join(', ')}` : ''}`);
    return;
  }
  const lines = checkOutputs(REPO, outputs);
  for (const l of lines) console.error(l);
  const goldens = [...outputs.entries()].filter(([k]) => k.endsWith('.goldens.json')).reduce((n, [, t]) => n + Object.keys(JSON.parse(t).goldens).length, 0);
  console.log(lines.length === 0 ? `surfaces ok (${[...outputs.keys()].filter((k) => k.startsWith(`${SLICE_DIR}/`)).length} surfaces, ${goldens} goldens)` : `surfaces FAIL (${lines.length} problems)`);
  if (lines.length) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
