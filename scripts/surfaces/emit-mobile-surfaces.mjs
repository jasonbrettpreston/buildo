#!/usr/bin/env node
// SPEC LINK: docs/specs/02-web-admin/126_maxbld_surface_standard.md §11b.2 (descriptor + content -> generator -> binding; regenerated, never
//            hand-edited), docs/specs/02-web-admin/135_mcfrontend_decisions_register.md FE-02 (generated, not hand-written), FE-31.
//
// MF-35 · McFrontend queue (plan v2 §2.1, §2.3; v3 §2.3). The mobile app cannot read files outside mobile/, so this generator copies, for every
// converted surface whose descriptor declares the mobile platform:
//   mobile/src/generated/surfaces/<id>.json                 the slice the binding reads: the descriptor's config values and the content strings;
//   mobile/__tests__/fixtures/surfaces/<id>.goldens.json    the committed mobile goldens (src/tests/fixtures/surfaces/<id>/*.mobile.json), for
//                                                            the mobile jest golden test (kept out of the app bundle).
// One source each: the descriptor, the content file, the goldens. Pure over committed files; no DB, no network.
// CLI: --write writes; --check (default) prints GEN-STALE / GEN-HAND-EDIT / GEN-STRAY lines and exits 1, else prints `surfaces ok (N surfaces, G goldens)`.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const MANIFEST = 'scripts/surfaces/_schema/converted-surfaces.json';
const PRESENTATION = 'scripts/surfaces/_schema/report-presentation.json'; // MF-48 Stage B: the REPORT lifecycle texts
const GOLDEN_ROOT = 'src/tests/fixtures/surfaces';
export const SLICE_DIR = 'mobile/src/generated/surfaces';
export const GOLDEN_COPY_DIR = 'mobile/__tests__/fixtures/surfaces';
const COMMENT = 'GENERATED by scripts/surfaces/emit-mobile-surfaces.mjs — do not edit';
const SHA_RE = /input_sha ([0-9a-f]{16})/;
// The descriptor config values a mobile binding may read (the SEARCH archetype's declared parameters, Spec 126 §3.1 row 4).
const CONFIG_KEYS = ['debounce_ms', 'min_query_len'];

const rj = (root, rel) => JSON.parse(fs.readFileSync(path.join(root, rel), 'utf8'));
const descriptorFile = (root, id) => {
  const walk = (rel) => fs.readdirSync(path.join(root, rel), { withFileTypes: true }).flatMap((e) => {
    const r = path.posix.join(rel, e.name);
    if (e.isDirectory()) return e.name === '_schema' ? [] : walk(r);
    return e.name === `${id}.descriptor.json` ? [r] : [];
  });
  const found = walk('scripts/surfaces');
  if (found.length !== 1) throw new Error(`emit-mobile-surfaces: ${found.length} descriptor files for ${id}`);
  return found[0];
};
const sha = (v) => crypto.createHash('sha256').update(JSON.stringify(v)).digest('hex').slice(0, 16);
const text = (v) => `${JSON.stringify(v, null, 2)}\n`;

/** Every output file (repo-relative) -> its exact text. */
export function buildOutputs(root = REPO) {
  const out = new Map();
  for (const id of rj(root, MANIFEST).converted) {
    const file = descriptorFile(root, id);
    const d = rj(root, file);
    if (!(d.identity?.platforms ?? []).includes('mobile')) continue;
    const content = rj(root, path.posix.join(path.posix.dirname(file), `${id}.content.json`));
    const config = Object.fromEntries(CONFIG_KEYS.filter((k) => d.config?.[k] !== undefined).map((k) => [k, d.config[k]]));
    const slice = { surface: id, config, content };
    out.set(`${SLICE_DIR}/${id}.json`, text({ $comment: `${COMMENT} (input_sha ${sha(slice)})`, ...slice }));
    const gdir = path.join(root, GOLDEN_ROOT, id);
    const names = fs.existsSync(gdir) ? fs.readdirSync(gdir).filter((f) => f.endsWith('.mobile.json')).sort() : [];
    const goldens = Object.fromEntries(names.map((f) => [f.slice(0, -'.mobile.json'.length), rj(root, `${GOLDEN_ROOT}/${id}/${f}`)]));
    out.set(`${GOLDEN_COPY_DIR}/${id}.goldens.json`, text({ $comment: `${COMMENT} (input_sha ${sha(goldens)})`, surface: id, goldens }));
  }
  // MF-48 Stage B (Spec 126 §11a.7 dated note 2026-11-12): a REPORT surface on mobile (the manifest's `report` list) gets a slice too: the approved
  // lifecycle texts of report-presentation.json (`states.lifecycle.<state>`, one home, never copied by hand) and its own content file (Retry, Back).
  // No goldens copy: its props goldens are read from the repo path by the mobile golden test (MF-48 Stage A, plan v2 L-5).
  for (const id of rj(root, MANIFEST).report ?? []) {
    const file = descriptorFile(root, id);
    if (!(rj(root, file).identity?.platforms ?? []).includes('mobile')) continue;
    const life = rj(root, PRESENTATION).states.lifecycle;
    const own = rj(root, path.posix.join(path.posix.dirname(file), `${id}.content.json`));
    const content = { ...Object.fromEntries(Object.entries(life).map(([k, v]) => [`states.lifecycle.${k}`, v])), ...own };
    const slice = { surface: id, config: {}, content };
    out.set(`${SLICE_DIR}/${id}.json`, text({ $comment: `${COMMENT} (input_sha ${sha(slice)})`, ...slice }));
  }
  return out;
}

/** Problem lines: a stale or hand-edited output, or a stray generated file no converted mobile surface owns. */
export function checkOutputs(root = REPO, outputs = buildOutputs(root)) {
  const lines = [];
  for (const [rel, fresh] of outputs) {
    const p = path.join(root, rel);
    const stored = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null;
    if (stored === fresh) continue;
    lines.push(SHA_RE.exec(stored ?? '')?.[1] === SHA_RE.exec(fresh)?.[1] ? `GEN-HAND-EDIT ${rel}` : `GEN-STALE ${rel}`);
  }
  for (const [dir, suffix] of [[SLICE_DIR, '.json'], [GOLDEN_COPY_DIR, '.goldens.json']]) {
    const abs = path.join(root, dir);
    if (!fs.existsSync(abs)) continue;
    for (const f of fs.readdirSync(abs).filter((x) => x.endsWith(suffix)).sort()) if (!outputs.has(`${dir}/${f}`)) lines.push(`GEN-STRAY ${dir}/${f}`);
  }
  return lines;
}

function main(argv) {
  const outputs = buildOutputs(REPO);
  if (argv.includes('--write')) {
    for (const [rel, t] of outputs) {
      fs.mkdirSync(path.dirname(path.join(REPO, rel)), { recursive: true });
      fs.writeFileSync(path.join(REPO, rel), t);
    }
    console.log(`wrote ${outputs.size} files`);
    return;
  }
  const lines = checkOutputs(REPO, outputs);
  for (const l of lines) console.error(l);
  const goldens = [...outputs.entries()].filter(([k]) => k.endsWith('.goldens.json')).reduce((n, [, t]) => n + Object.keys(JSON.parse(t).goldens).length, 0);
  console.log(lines.length === 0 ? `surfaces ok (${[...outputs.keys()].filter((k) => k.startsWith(`${SLICE_DIR}/`)).length} surfaces, ${goldens} goldens)` : `surfaces FAIL (${lines.length} problems)`);
  if (lines.length) process.exitCode = 1;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
