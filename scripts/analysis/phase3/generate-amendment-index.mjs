// SPEC LINK: docs/specs/01-pipeline/78_optimal_lot_configuration.md P5.10 field_citations (amendment status of every cited unit)
// Handbook:  Spec 133 m.188 (M-188 part 6); HELD on P3-Q1 / P3-Q15
//
// Generates docs/reference/maxbld-amendment-index.json: unit id -> the WORST amendment status of the regulation row that holds the
// unit (none < in_force < partially_in_force < not_verified), for exactly the units Layer 2 can cite (bylaw-layer2-input.json).
// `--write` writes it, `--check` fails on drift. Lives outside scripts/analysis/bylaw so it is not a Layer 1 input.

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export const OUT_REL = 'docs/reference/maxbld-amendment-index.json';
const RANK = { none: 0, in_force: 1, partially_in_force: 2, not_verified: 3 };

export function buildIndexFile({ root }) {
  const provisions = JSON.parse(fs.readFileSync(path.join(root, 'docs/reference/bylaw-provisions.json'), 'utf8'));
  const input = JSON.parse(fs.readFileSync(path.join(root, 'docs/reference/bylaw-layer2-input.json'), 'utf8'));
  // regulation id -> worst amendment status of its provisions row (a Layer 2 unit id is <regulation_id>#<clause>)
  const byReg = {};
  for (const row of provisions.rows) {
    let worst = 'none';
    for (const a of row.amendments || []) {
      const s = Object.prototype.hasOwnProperty.call(provisions.amendment_statuses, a.bylaw) ? provisions.amendment_statuses[a.bylaw] : 'not_verified';
      const r = RANK[s] === undefined ? RANK.not_verified : RANK[s];
      if (r > RANK[worst]) worst = RANK[s] === undefined ? 'not_verified' : s;
    }
    byReg[row.regulation_id] = worst;
  }
  const index = {};
  const unmatched = new Set();
  for (const u of [...input.body.units].sort((a, b) => (a.unit_id < b.unit_id ? -1 : 1))) {
    if (Object.prototype.hasOwnProperty.call(byReg, u.regulation_id)) index[u.unit_id] = byReg[u.regulation_id];
    else { index[u.unit_id] = 'not_verified'; unmatched.add(u.regulation_id); } // no provisions row to verify against: not verified
  }
  return {
    $comment: 'GENERATED by scripts/analysis/phase3/generate-amendment-index.mjs --write (never hand-edited). Unit id -> worst amendment status of its regulation row (bylaw-provisions.json), for the units in docs/reference/bylaw-layer2-input.json; a unit whose regulation has no provisions row reads not_verified. Read by scripts/lib/compute/compute-maxbld-scenarios.js for field_citations (Spec 78 P5.10).',
    layer2_table_version: input.table_version,
    regulations_without_provisions_row: [...unmatched].sort(),
    index,
  };
}

export function run({ root, mode }) {
  const fresh = buildIndexFile({ root });
  const text = `${JSON.stringify(fresh, null, 1)}\n`;
  const file = path.join(root, OUT_REL);
  const drift = !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text;
  if (mode === 'write') fs.writeFileSync(file, text);
  return { drift: mode === 'write' ? false : drift, units: Object.keys(fresh.index).length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const mode = process.argv.includes('--write') ? 'write' : 'check';
  const r = run({ root: process.cwd(), mode });
  console.log(`[maxbld-amendment-index] ${mode === 'write' ? 'written' : r.drift ? 'DRIFT' : 'clean'} - ${r.units} units`);
  if (r.drift) process.exit(1);
}
