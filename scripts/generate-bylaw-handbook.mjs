#!/usr/bin/env node
// SPEC LINK: docs/specs/01-pipeline/69a_mcbylaw_register.md M-260 (Spec 133, the By-law Handbook; operator y 2026-10-21,
//            `2026-10-21-chat-batch-m-43#CHAT-43`); docs/specs/01-pipeline/124_step_standard_policy.md §5 R-GU (the form it
//            mirrors), R-GV (standard + policy pairs), R-GW (role banner); 124a R-IY (the tooling, keyed by spec id)
// ---------------------------------------------------------------------------
// By-law handbook generator → docs/specs/01-pipeline/133_bylaw_handbook.md, Spec 133 — By-law Handbook. The same form as
// Spec 132 (scripts/generate-step-handbook.mjs): a generated reading spec with a Status line, a role banner (generated
// handbook), an authority sentence and the citation form `Spec 133 §<line id> (M-xx / LC-xx)`; `--check` runs at pre-commit;
// `spec-split-check` arm (iii-b) resolves the citations and arm (iv-b) holds the size cap (both keyed by spec id,
// scripts/analysis/gates/rule-map.mjs HANDBOOKS).
//
// What differs from Spec 132 is the source. Spec 132's rule map is curated; the by-law registers hold hundreds of rows,
// so the rule map (scripts/analysis/bylaw/_schema/bylaw-rule-map.json) is itself GENERATED from them, never hand-written:
// one line per register row (line id m.<n> for a Spec 69a M-row, lc.<n> for a Spec 131 LC-row), each citing its row.
//   Authority (policy)    Spec 69/69a M-rows (by-laws) and Spec 131 LC-rows (lot configuration).
//   Standard + behaviour  Spec 68 (by-laws) and Spec 78 (lot configuration).
// The handbook renders a one-line reading summary of each row (its bold headline, status and "Enforced by" cell). Rulings,
// their reasons and their dated notes stay in the registers; a new ruling is a new register row, never an edit here.
//
// Usage:
//   node scripts/generate-bylaw-handbook.mjs --write   # regenerate the rule map and the handbook
//   node scripts/generate-bylaw-handbook.mjs --check   # exit 1 if either is stale; exit 2 on bad usage
// Deterministic: no clock, no DB, no network.
// ---------------------------------------------------------------------------

import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { HANDBOOKS } from './analysis/gates/rule-map.mjs';
import { readBylawRegisterRows, BYLAW_REGISTERS, GENERAL_FAMILY } from './analysis/bylaw/bylaw-register.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const SPEC = HANDBOOKS['133'];
const MAP_OUT = path.join(ROOT, SPEC.ruleMapRel);
const OUTPUT = path.join(ROOT, SPEC.handbookRel);
const HISTORY = 'history';

const PROVISIONS_REL = 'docs/reference/bylaw-provisions.json';
const FAMILY_PREFIX = 'fam-';

/** Sort key: zone-chapter families (40.10) numerically, then 10.5 families, then chapters 150 / 800 / 900, then general. */
function familyRank(f) {
  if (f === GENERAL_FAMILY) return [3, []];
  const nums = f.split('.').map(Number);
  if (f.startsWith('10.5.')) return [1, nums];
  if (nums.length === 1) return [2, nums];
  return [0, nums];
}
export function compareFamilies(x, y) {
  const [rx, nx] = familyRank(x);
  const [ry, ny] = familyRank(y);
  if (rx !== ry) return rx - ry;
  for (let i = 0; i < Math.max(nx.length, ny.length); i += 1) if ((nx[i] ?? -1) !== (ny[i] ?? -1)) return (nx[i] ?? -1) - (ny[i] ?? -1);
  return 0;
}

/** Headings the repo already holds: the by-law article title for a family, from the first zone chapter that has it. */
function readFamilyTitles(root = ROOT) {
  const file = path.join(root, PROVISIONS_REL);
  if (!fs.existsSync(file)) return { titleFor: () => undefined };
  const articles = new Map();
  for (const r of JSON.parse(fs.readFileSync(file, 'utf8')).rows) if (r.article && r.article_title && !articles.has(r.article)) articles.set(r.article, r.article_title);
  const zones = ['10', '20', '40', '60', '80'];
  const titleFor = (family) => {
    if (family.startsWith('10.5.')) return articles.get(family);
    for (const z of zones) if (articles.has(`10.${z}.${family}`)) return articles.get(`10.${z}.${family}`);
    return undefined;
  };
  return { titleFor };
}

const HISTORY_SECTION = {
  id: HISTORY,
  title: 'History (not in force)',
  intro: 'Rows retired, folded or superseded. Listed only so old citations resolve. Nothing here is a rule you must follow.',
};
const sectionIdOf = (row) => (row.history ? HISTORY : `${FAMILY_PREFIX}${row.family}`);

const lineIdOf = (id) => id.toLowerCase().replace('-', '.');

/** The rule map, built from the register rows. Structure only: line text is read from the register at render time. */
export function buildRuleMap(rows) {
  return {
    $comment: [
      'Spec 133 (By-law Handbook) rule map. GENERATED by `node scripts/generate-bylaw-handbook.mjs --write` from the Spec 69a M-rows and the Spec 131 LC-rows (Spec 69a M-260, operator y 2026-10-21, 2026-10-21-chat-batch-m-43#CHAT-43). Do not hand-edit: `--check` runs at pre-commit.',
      'One line per register row, one rule per line. A rule is the row id; a dated note belongs to the row it follows. Status lives in the register row; here it only places the line (active, owed or history). A line sits in the provision family derived from the FIRST clause its row cites (scripts/analysis/bylaw/bylaw-register.mjs familyOf); a row citing no clause is general.',
    ],
    contract_version: 1,
    meta: {
      decided: 'operator y 2026-10-20 (2026-10-20-spec132-rulings#HANDBOOK); built on operator y 2026-10-21 (2026-10-21-chat-batch-m-43#CHAT-43)',
      authority: 'Spec 69/69a M-rows and Spec 131 LC-rows (policy) + Spec 68 and Spec 78 (standard and behaviour)',
      reading_surface: `Spec 133 — By-law Handbook, ${SPEC.handbookRel} (generated from this file and the registers)`,
      pairs: [
        { family: 'By-laws', standard: 'Spec 68', policy: 'Spec 69/69a (M-rows)' },
        { family: 'Lot configuration', standard: 'Spec 78', policy: 'Spec 131 (LC-rows)' },
      ],
      generated_from: BYLAW_REGISTERS.map((r) => r.rel),
    },
    sections: [...new Set(rows.filter((r) => !r.history).map((r) => r.family))].sort(compareFamilies).map((f) => ({ id: `${FAMILY_PREFIX}${f}`, family: f })).concat([{ id: HISTORY }]),
    lines: rows.map((r) => ({ id: lineIdOf(r.id), section: sectionIdOf(r) })),
    rules: rows.map((r) => ({
      id: r.id,
      kind: r.kind === 'M' ? 'm-row' : 'lc-row',
      status: r.history ? 'history' : r.owed ? 'owed' : 'active',
      handbook_line: lineIdOf(r.id),
      source: { register: true, file: r.file, anchor: r.struck ? `~~${r.id}~~` : `**${r.id}**` },
    })),
  };
}

/** Findings the map has against the registers: an unmapped row, a stale rule, a missing anchor, a line with no rule. */
export function mapFindings(map, rows, read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8')) {
  const out = [];
  const ids = new Set(rows.map((r) => r.id));
  const mapped = new Set();
  for (const r of map.rules) {
    if (mapped.has(r.id)) out.push(`${r.id} is mapped twice`);
    mapped.add(r.id);
    if (!ids.has(r.id)) out.push(`${r.id} is in the map but not in a register`);
    else if (!read(r.source.file).includes(`| ${r.source.anchor} |`)) out.push(`${r.id}: anchor ${r.source.anchor} not found in ${r.source.file}`);
  }
  for (const id of ids) if (!mapped.has(id)) out.push(`${id} is a register row with no rule-map entry`);
  const lineIds = new Set(map.lines.map((l) => l.id));
  for (const l of map.lines) if (map.rules.filter((r) => r.handbook_line === l.id).length !== 1) out.push(`line ${l.id} does not cite exactly one rule`);
  for (const r of map.rules) if (!lineIds.has(r.handbook_line)) out.push(`${r.id}: handbook_line ${r.handbook_line} is not a line`);
  return out;
}

function renderLine(row) {
  const notes = row.notes ? ` · +${row.notes} dated note${row.notes === 1 ? '' : 's'}` : '';
  const enforced = row.enforcedBy ? ` · Enforced by: ${row.enforcedBy}` : '';
  return `- **${lineIdOf(row.id)}** ${row.headline}\n  Status: ${row.status}${enforced}\n  Rules: \`${row.id}\` (${row.spec})${notes}\n`;
}

// Paths the static header names; each must exist (the generator's one fact lock, like Spec 132's backticked-path check).
const NAMED_PATHS = Object.freeze([
  'scripts/generate-bylaw-handbook.mjs',
  'scripts/analysis/bylaw/bylaw-register.mjs',
  'scripts/analysis/gates/rule-map.mjs',
  'src/tests/spec133-bylaw-handbook.logic.test.ts',
  'docs/specs/01-pipeline/68_mcbylaw_standard.md',
  'docs/specs/01-pipeline/69_mcbylaw_policy.md',
  'docs/specs/01-pipeline/69a_mcbylaw_register.md',
  'docs/specs/01-pipeline/78_optimal_lot_configuration.md',
  'docs/specs/01-pipeline/131_lot_configuration_policy.md',
  'docs/specs/01-pipeline/122_split_manifest.json',
]);

export function render(map, rows) {
  const problems = mapFindings(map, rows);
  if (problems.length) throw new Error(`[bylaw-handbook] the rule map does not match the registers:\n  - ${problems.join('\n  - ')}`);
  const missing = NAMED_PATHS.filter((p) => !fs.existsSync(path.join(ROOT, p)));
  if (missing.length) throw new Error(`[bylaw-handbook] a path the handbook names does not exist: ${missing.join(', ')}`);
  const byId = new Map(rows.map((r) => [r.id, r]));
  const example = byId.get('M-176') || rows[0];
  const inForce = rows.filter((r) => !r.history);
  const owed = inForce.filter((r) => r.owed);
  const out = [];
  out.push('# SPEC 133 — By-law Handbook');
  out.push('');
  out.push('**Status:** GENERATED');
  out.push('');
  out.push(`> **Role: generated handbook.** Authority: ${map.meta.authority}; this spec is GENERATED from bylaw-rule-map.json — do not hand-edit. It is the reading surface of the by-law pair and the lot-configuration pair (Spec 124 R-GV). If this page and a register row disagree, the register row governs on policy and Spec 68 or Spec 78 on the standard and behaviour; fix the register or the generator, never this page. A new ruling is a new row in its register, never a line here.`);
  out.push('>');
  out.push(`> **Citation form.** \`Spec 133 §<line id> (M-xx / LC-xx)\`, e.g. \`Spec 133 §${lineIdOf(example.id)} (${example.id})\`. The line id is the bold id that starts each line (m.<n> for a Spec 69a M-row, lc.<n> for a Spec 131 LC-row); the rule id is the register row it summarises. \`spec-split-check --check\` resolves every such citation in the repo and fails one whose line does not exist or whose rule maps to another line (arm iii-b).`);
  out.push('');
  out.push('<!-- GENERATED by `node scripts/generate-bylaw-handbook.mjs --write`. Do not edit by hand: `--check` runs at pre-commit. -->');
  out.push('');
  out.push('**"Comply with Spec 133"** means: for by-law and lot-configuration work, read the lines that cover the provision family you touch, then follow the register row each cites. Every line cites its binding rule id; the row in `docs/specs/01-pipeline/69a_mcbylaw_register.md` or `docs/specs/01-pipeline/131_lot_configuration_policy.md` is the authority, with its reasons, evidence and dated notes.');
  out.push('');
  out.push('## 1. Standard and policy pairs');
  out.push('');
  out.push('| Family | Standard and behaviour (what is built) | Policy register (what is ruled) |');
  out.push('|---|---|---|');
  out.push('| By-laws | Spec 68 (`docs/specs/01-pipeline/68_mcbylaw_standard.md`) | Spec 69/69a, the M-rows (`docs/specs/01-pipeline/69_mcbylaw_policy.md`, `docs/specs/01-pipeline/69a_mcbylaw_register.md`) |');
  out.push('| Lot configuration | Spec 78 (`docs/specs/01-pipeline/78_optimal_lot_configuration.md`) | Spec 131, the LC-rows (`docs/specs/01-pipeline/131_lot_configuration_policy.md`) |');
  out.push('');
  out.push(`On a policy question the register governs; on the standard and behaviour, Spec 68 or Spec 78 does (Spec 124 R-GV). The same provision is ruled alike in every zone copy (Spec 68 §5a part 2), so read by provision family, not by zone suffix.`);
  out.push('');
  out.push(`**What is generated.** Everything below, from the two registers by \`scripts/generate-bylaw-handbook.mjs\` (reader: \`scripts/analysis/bylaw/bylaw-register.mjs\`). The rule map \`${SPEC.ruleMapRel}\` is generated from the same rows, not hand-written; \`src/tests/spec133-bylaw-handbook.logic.test.ts\` locks that every register row has exactly one line and every line cites exactly one row. Size: a measured cap in \`docs/specs/01-pipeline/122_split_manifest.json\` \`generated_size_caps["133"]\` (\`spec-split-check\` arm iv-b), raised only by a reviewed hand-edit.`);
  out.push('');
  out.push(`**Rules rendered: ${rows.length}** (${rows.filter((r) => r.kind === 'M').length} M-rows, ${rows.filter((r) => r.kind === 'LC').length} LC-rows): ${inForce.length} in force (${owed.length} with an OWED marker), ${rows.length - inForce.length} history. Rules are grouped by provision family, derived from the first clause a row cites (a zone-chapter clause 10.20.40.10 and 10.80.40.10 are both family 40.10; 10.5, 150, 800 and 900 keep their chapter; a row citing no clause is general / cross-cutting), so the mirrored zone chapters read together. Line ids do not depend on the grouping. Each line: reading headline, the register's status, its "Enforced by" cell, then the rule id and the number of dated notes under it.`);
  out.push('');
  out.push('**Contents.** 1 Standard and policy pairs · 2 Rules by provision family · 3 Rows with an OWED marker · 4 History');
  out.push('');
  const titles = readFamilyTitles();
  out.push('## 2. Rules by provision family');
  out.push('');
  for (const sec of map.sections.filter((x) => x.family)) {
    const f = sec.family;
    const members = map.lines.filter((x) => x.section === sec.id).map((l) => byId.get(map.rules.find((r) => r.handbook_line === l.id).id));
    const clauses = [...new Set(members.map((r) => r.clause).filter(Boolean))];
    const title = titles.titleFor ? titles.titleFor(f) : undefined;
    if (f === GENERAL_FAMILY) out.push('### General / cross-cutting');
    else if (/^[0-9]+$/.test(f)) out.push(`### Chapter ${f}`);
    else out.push(`### ${f}${title ? ` — ${title}` : ''}`);
    out.push('');
    out.push(f === GENERAL_FAMILY ? 'Rows that cite no by-law clause: process, method and cross-cutting rulings.' : `First clause cited: ${clauses.join(', ')}.`);
    out.push('');
    for (const r of members) out.push(renderLine(r));
  }
  let n = 3;
  out.push(`## ${n}. Rows with an OWED marker (${owed.length} in force)`);
  out.push('');
  out.push('The register marks work still owed on these rows (a lock, a step commit, a ruling). The register row says what and who; this list only finds them.');
  out.push('');
  out.push('| Rule | Line | Status |');
  out.push('|---|---|---|');
  for (const r of owed) out.push(`| ${r.id} | ${lineIdOf(r.id)} | ${r.status.replace(/\|/g, '/')} |`);
  out.push('');
  n += 1;
  out.push(`## ${n}. History`);
  out.push('');
  out.push(HISTORY_SECTION.intro);
  out.push('');
  for (const l of map.lines.filter((x) => x.section === HISTORY)) out.push(renderLine(byId.get(map.rules.find((r) => r.handbook_line === l.id).id)));
  out.push('## Operating Boundaries');
  out.push('');
  out.push('### Target Files');
  out.push('- `scripts/generate-bylaw-handbook.mjs` (the generator; `--write` / `--check`)');
  out.push('- `scripts/analysis/bylaw/bylaw-register.mjs` (the one reader of the by-law registers)');
  out.push('- `scripts/analysis/gates/rule-map.mjs` (the handbook registry keyed by spec id)');
  out.push(`- \`${SPEC.ruleMapRel}\` (the generated rule map)`);
  out.push('- `src/tests/spec133-bylaw-handbook.logic.test.ts` (the lock)');
  out.push('');
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`;
}

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

function main(argv) {
  const known = new Set(['--write', '--check']);
  const unknown = argv.filter((a) => !known.has(a));
  const write = argv.includes('--write');
  const check = argv.includes('--check');
  if (unknown.length || write === check) {
    console.error('usage: node scripts/generate-bylaw-handbook.mjs --write | --check');
    process.exitCode = 2;
    return;
  }
  let map;
  let text;
  try {
    const rows = readBylawRegisterRows(ROOT);
    map = buildRuleMap(rows);
    text = render(map, rows);
  } catch (err) {
    console.error(String(err && err.message ? err.message : err));
    process.exitCode = 1;
    return;
  }
  const mapText = json(map);
  if (check) {
    const stale = [];
    if (!fs.existsSync(MAP_OUT) || fs.readFileSync(MAP_OUT, 'utf8') !== mapText) stale.push(SPEC.ruleMapRel);
    if (!fs.existsSync(OUTPUT) || fs.readFileSync(OUTPUT, 'utf8') !== text) stale.push(SPEC.handbookRel);
    if (stale.length) {
      console.error(`[bylaw-handbook] ${stale.join(' and ')} stale — run node scripts/generate-bylaw-handbook.mjs --write`);
      process.exitCode = 1;
      return;
    }
    console.log(`[bylaw-handbook] ${SPEC.handbookRel} is up to date (${map.rules.length} rules)`);
    return;
  }
  fs.mkdirSync(path.dirname(MAP_OUT), { recursive: true });
  fs.writeFileSync(MAP_OUT, mapText);
  fs.writeFileSync(OUTPUT, text);
  console.log(`[bylaw-handbook] wrote ${SPEC.ruleMapRel} and ${SPEC.handbookRel} (${text.split('\n').length - 1} lines, ${map.rules.length} rules)`);
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) main(process.argv.slice(2));
